create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  username text not null unique,
  display_name text not null,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.leafs (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.profiles(id) on delete cascade,
  parent_id bigint references public.leafs(id) on delete cascade,
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_leafs_author_id on public.leafs(author_id);
create index if not exists idx_leafs_parent_id on public.leafs(parent_id);
create index if not exists idx_leafs_created_at on public.leafs(created_at desc);

create table public.leaf_likes (
  id bigint generated by default as identity primary key,
  leaf_id bigint not null references public.leafs(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (leaf_id, user_id)
);

create index if not exists idx_leaf_likes_leaf_id on public.leaf_likes(leaf_id);
create index if not exists idx_leaf_likes_user_id on public.leaf_likes(user_id);

create or replace function public.handle_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at
before update on public.profiles
for each row
execute function public.handle_updated_at();

alter table public.profiles enable row level security;
alter table public.leafs enable row level security;
alter table public.leaf_likes enable row level security;

create policy "Users can view profiles"
on public.profiles for select using (true);

create policy "Users can create their own profile"
on public.profiles for insert with check (auth.uid() = id);

create policy "Users can update their own profile"
on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);

create policy "Users can view leaves"
on public.leafs for select using (true);

create policy "Users can create leaves"
on public.leafs for insert with check (auth.uid() = author_id);

create policy "Users can update or delete their own leaves"
on public.leafs for update using (auth.uid() = author_id) with check (auth.uid() = author_id);
create policy "Users can delete their own leaves"
on public.leafs for delete using (auth.uid() = author_id);

create policy "Users can view likes"
on public.leaf_likes for select using (true);

create policy "Users can create likes"
on public.leaf_likes for insert with check (auth.uid() = user_id);

create policy "Users can delete their own likes"
on public.leaf_likes for delete using (auth.uid() = user_id);

create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, username, display_name)
  values (
    new.id,
    new.email,
    split_part(new.email, '@', 1) || '_' || substr(md5(random()::text), 1, 6),
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1))
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.create_profile_for_new_user();

create or replace view public.leaf_feed as
select
  l.id,
  l.author_id,
  p.username,
  p.display_name,
  l.content,
  l.parent_id,
  l.created_at,
  (
    select count(*)
    from public.leaf_likes likes
    where likes.leaf_id = l.id
  ) as like_count
from public.leafs l
left join public.profiles p on p.id = l.author_id;

