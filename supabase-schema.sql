create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, username, display_name, bio, role, badge_tier)
  values (
    new.id,
    new.email,
    split_part(new.email, '@', 1) || '_' || substr(md5(random()::text), 1, 6),
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)),
    '',
    'user',
    'none'
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.create_profile_for_new_user();

create or replace view public.leaf_feed as
select
  l.id,
  l.author_id,
  p.username,
  p.display_name,
  p.badge_tier,
  p.role,
  l.content,
  l.parent_id,
  l.created_at,
  (
    select count(*)
    from public.leaf_likes likes
    where likes.leaf_id = l.id
  ) as like_count
from public.leafs l
left join public.profiles p on p.id = l.author_id
where l.deleted_at is null
and l.hidden_by_staff = false;

