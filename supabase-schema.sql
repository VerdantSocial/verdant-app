create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  username text not null unique,
  display_name text not null,
  bio text default '',
  avatar_url text,
  role text not null default 'user' check (role in ('user', 'staff', 'admin')),
  badge_tier text not null default 'none' check (badge_tier in ('none', 'verified', 'official')),
  is_banned boolean not null default false,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.verification_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  reason text default '',
  created_at timestamptz not null default now(),
  reviewed_by uuid references public.profiles(id),
  reviewed_at timestamptz
);

create table if not exists public.leafs (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.profiles(id) on delete cascade,
  parent_id bigint references public.leafs(id) on delete cascade,
  content text not null,
  hidden_by_staff boolean not null default false,
  deleted_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists idx_leafs_author_id on public.leafs(author_id);
create index if not exists idx_leafs_parent_id on public.leafs(parent_id);
create index if not exists idx_leafs_created_at on public.leafs(created_at desc);

create table if not exists public.leaf_likes (
  id bigint generated by default as identity primary key,
  leaf_id bigint not null references public.leafs(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (leaf_id, user_id)
);

create index if not exists idx_leaf_likes_leaf_id on public.leaf_likes(leaf_id);
create index if not exists idx_leaf_likes_user_id on public.leaf_likes(user_id);

create or replace function public.handle_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at
before update on public.profiles
for each row
execute function public.handle_updated_at();

